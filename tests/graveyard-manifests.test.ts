// Prompt 15: manifests, js-dos bundles and the public catalogue for the Graveyard page.
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { resolve } from 'node:path';
import { GraveyardManifest } from '@afterlife/emulator';
import { unzipSync } from 'fflate';
import { describe, expect, it } from 'vitest';
import { APPS, publishAll } from '../scripts/graveyard-publish';
import { GRAVEYARD } from './helpers/graveyard';

const root = resolve(__dirname, '..');
const pub = resolve(root, 'apps/web/public/graveyard');
const manifest = (id: string) =>
  GraveyardManifest.parse(
    JSON.parse(readFileSync(resolve(GRAVEYARD, id, 'manifest.json'), 'utf8')),
  );

describe('the three dead apps', () => {
  it('are shifa, iqra and barkat', () => {
    expect(APPS).toEqual(['shifa', 'iqra', 'barkat']);
  });
});

describe.each(['shifa', 'iqra', 'barkat'])('%s manifest', (id) => {
  const m = manifest(id);

  it('is valid and its id matches its folder', () => {
    expect(m.id).toBe(id);
  });

  it('names the built executable and data files that really exist', () => {
    expect(existsSync(resolve(GRAVEYARD, 'dist', id, m.executable))).toBe(true);
    const built = readdirSync(resolve(GRAVEYARD, 'dist', id))
      .filter((f) => f.endsWith('.DBF'))
      .sort();
    expect([...m.dataFiles].sort()).toEqual(built);
  });

  it('uses the same DOS clock as the scenarios', () => {
    const env = readFileSync(resolve(GRAVEYARD, id, 'build.env'), 'utf8');
    const t = /^DOS_TIME="(.+)"$/m.exec(env)?.[1] ?? '1998-07-15 10:00:00';
    expect(m.dosTime).toBe(t);
    expect(Number(m.dosTime.slice(0, 4))).toBe(m.born);
  });

  it('every hidden rule and bug is demonstrated by a scenario that exists', () => {
    const scenarios = readdirSync(resolve(GRAVEYARD, id, 'scenarios')).map((f) =>
      f.replace(/\.(keys|time)$/, ''),
    );
    for (const item of [...m.knownRules, ...m.knownBugs])
      for (const s of item.scenarios) expect(scenarios, `${item.id} -> ${s}`).toContain(s);
    expect(m.knownBugs.length).toBeGreaterThanOrEqual(1);
  });

  it('the preview is a real screen dump from DOSBox', () => {
    expect(existsSync(resolve(GRAVEYARD, 'fixtures', id, m.preview))).toBe(true);
  });
});

describe('bundles and catalogue (generated by pnpm graveyard:publish)', () => {
  const fresh = publishAll();

  it.each(['shifa', 'iqra', 'barkat'])('%s.jsdos is committed and up to date', (id) => {
    const file = resolve(pub, `${id}.jsdos`);
    expect(existsSync(file), 'run pnpm graveyard:publish').toBe(true);
    expect(new Uint8Array(readFileSync(file)), 'run pnpm graveyard:publish').toEqual(
      fresh.bundles[id],
    );
  });

  it.each(['shifa', 'iqra', 'barkat'])(
    '%s.jsdos holds the dist files byte for byte and starts the EXE',
    (id) => {
      const m = manifest(id);
      const zip = unzipSync(new Uint8Array(readFileSync(resolve(pub, `${id}.jsdos`))));
      for (const f of [m.executable, ...m.dataFiles])
        expect(zip[f], f).toEqual(new Uint8Array(readFileSync(resolve(GRAVEYARD, 'dist', id, f))));
      expect(new TextDecoder().decode(zip['.jsdos/dosbox.conf'])).toContain(
        `\nc:\n${m.executable}\n`,
      );
    },
  );

  it('the catalogue is committed and up to date', () => {
    expect(
      readFileSync(resolve(root, 'apps/web/lib/graveyard-catalog.json'), 'utf8'),
      'run pnpm graveyard:publish',
    ).toBe(fresh.catalog);
  });

  it('the catalogue never contains the hidden rules or bugs', () => {
    const catalog = readFileSync(resolve(root, 'apps/web/lib/graveyard-catalog.json'), 'utf8');
    expect(catalog).not.toMatch(/knownRules|knownBugs|scenarios/);
    for (const id of APPS)
      for (const item of [...manifest(id).knownRules, ...manifest(id).knownBugs])
        expect(catalog).not.toContain(item.text);
  });

  it('nothing hidden is published under apps/web/public either', () => {
    for (const f of readdirSync(pub)) expect(f).toMatch(/\.jsdos$/);
  });

  it('the catalogue preview is the first screen of each app', () => {
    const catalog = JSON.parse(
      readFileSync(resolve(root, 'apps/web/lib/graveyard-catalog.json'), 'utf8'),
    );
    expect(catalog.apps.map((a: { id: string }) => a.id)).toEqual(APPS);
    expect(catalog.apps[0].preview[0]).toContain('SHIFA MEDICAL STORE');
    expect(catalog.apps[0].preview).toHaveLength(25);
    expect(catalog.disclosure).toMatch(/written by our team/);
  });
});
